#!/usr/bin/env node
// Bakes the Lucide glyphs the UI uses into src/vue/lucide-icons.js so the
// renderer never reaches for a CDN. Re-run after adding a name to ICONS.
const fs = require('fs');
const path = require('path');

const ICONS = [
  // TopNav / CollapsedRail
  'chevron-down', 'sun', 'moon', 'settings', 'panel-left-open', 'panel-left-close',
  // Section tabs
  'sparkles', 'square-kanban', 'book-open', 'brain', 'chart-no-axes-column',
  'folder', 'users', 'notebook-pen',
  // Command bar / filters
  'search', 'plus', 'list', 'layout-grid', 'star', 'archive', 'calendar-days',
  'refresh-cw', 'folder-plus', 'circle-dot',
  // Projects tab — container-visibility toggle
  'container',
  // Session view
  'git-branch', 'x', 'maximize-2', 'circle', 'square', 'folder-open', 'terminal',
  'square-arrow-out-up-right', 'ellipsis',
  // Session side panel — rail toggles (changes / containers / shell)
  'panel-right-open', 'panel-right-close', 'file-diff',
  // Accounts view
  'copy', 'check', 'key-round', 'file-json', 'triangle-alert', 'circle-check',
  // Session context menu
  'pin', 'pin-off', 'git-fork', 'trash-2', 'message-square', 'square-stop', 'pencil',
  // Agent files — scheduled tasks
  'play',
];

const SRC = path.join(__dirname, '..', 'node_modules', 'lucide-static', 'icons');
const OUT = path.join(__dirname, '..', 'src', 'vue', 'lucide-icons.js');

const entries = ICONS.map((name) => {
  const file = path.join(SRC, `${name}.svg`);
  if (!fs.existsSync(file)) throw new Error(`lucide icon not found: ${name}`);
  // Keep only the glyph body — SbIcon.vue supplies <svg> with its own sizing.
  const body = fs.readFileSync(file, 'utf8')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s+/g, ' ')
    .trim();
  return `  ${JSON.stringify(name)}: ${JSON.stringify(body)},`;
}).join('\n');

fs.writeFileSync(OUT, `// GENERATED by scripts/generate-lucide-module.js — do not edit by hand.
// Glyph bodies from lucide-static; SbIcon.vue wraps them in a sized <svg>.
export const LUCIDE = {
${entries}
};
`);

console.log(`wrote ${OUT} (${ICONS.length} icons)`);
