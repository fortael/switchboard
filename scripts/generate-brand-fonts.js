#!/usr/bin/env node
// Bundles Inter + JetBrains Mono into public/fonts/ and writes the matching
// @font-face rules to public/css/fonts-brand.css.
//
// Why: public/style.css declares both families against fonts.gstatic.com URLs
// that 404, so the whole UI silently fell back to system fonts. A desktop app
// should not be fetching its brand type over the network anyway.
//
// fonts-brand.css is linked AFTER style.css. Later @font-face rules win for
// overlapping (family, weight, unicode-range), which is what neutralises the
// dead remote declarations without editing them.
const fs = require('fs');
const path = require('path');

// Subsets the UI actually needs: the chrome is English, session transcripts
// are frequently Russian.
const SUBSETS = ['latin', 'latin-ext', 'cyrillic', 'cyrillic-ext'];

const FAMILIES = [
  { cssFamily: 'Inter', pkg: '@fontsource-variable/inter', filePrefix: 'inter' },
  { cssFamily: 'JetBrains Mono', pkg: '@fontsource-variable/jetbrains-mono', filePrefix: 'jetbrains-mono' },
];

const ROOT = path.join(__dirname, '..');
const OUT_FONTS = path.join(ROOT, 'public', 'fonts');
const OUT_CSS = path.join(ROOT, 'public', 'css', 'fonts-brand.css');

// Pull the unicode-range straight out of the package's own CSS so the subsets
// stay correct when the package updates.
function unicodeRangesFor(pkg) {
  const css = fs.readFileSync(path.join(ROOT, 'node_modules', pkg, 'wght.css'), 'utf8');
  const ranges = {};
  const blocks = css.split('@font-face');
  for (const block of blocks) {
    const file = block.match(/url\(\.\/files\/([^)]+)\.woff2\)/);
    const range = block.match(/unicode-range:\s*([^;]+);/);
    if (file && range) ranges[file[1]] = range[1].trim();
  }
  return ranges;
}

fs.mkdirSync(OUT_FONTS, { recursive: true });
fs.mkdirSync(path.dirname(OUT_CSS), { recursive: true });

const blocks = [];

for (const family of FAMILIES) {
  const ranges = unicodeRangesFor(family.pkg);
  for (const subset of SUBSETS) {
    const base = `${family.filePrefix}-${subset}-wght-normal`;
    const src = path.join(ROOT, 'node_modules', family.pkg, 'files', `${base}.woff2`);
    if (!fs.existsSync(src)) throw new Error(`missing font file: ${src}`);
    if (!ranges[base]) throw new Error(`no unicode-range for ${base}`);
    fs.copyFileSync(src, path.join(OUT_FONTS, `${base}.woff2`));
    blocks.push(`/* ${base} */
@font-face {
  font-family: '${family.cssFamily}';
  font-style: normal;
  font-display: swap;
  font-weight: 100 900;
  src: url('../fonts/${base}.woff2') format('woff2-variations');
  unicode-range: ${ranges[base]};
}`);
  }
}

fs.writeFileSync(OUT_CSS, `/* GENERATED by scripts/generate-brand-fonts.js — do not edit by hand.

   Bundled Inter + JetBrains Mono. Must load AFTER public/style.css, whose
   remote @font-face declarations for these families point at dead
   fonts.gstatic.com URLs; the later rules here win and keep the app off the
   network for its own type. */

${blocks.join('\n\n')}
`);

console.log(`wrote ${OUT_CSS} (${blocks.length} faces) and ${blocks.length} woff2 files into public/fonts/`);
